#The name of the class always starts with a capital letter.
#In this example, we created two objects of the Animals class, cat and dog.
class Animals():
    name = ""
    sound = ""
    type = ""
    color = ""

cat = Animals()
#The dot operetor is used to acess the properties/characteristics of the objects.
cat.name = "Whiskers"
cat.sound = "Meow"
cat.type = "Feline"
cat.color = "Black and White"

print("\nName:", cat.name)
print("Sound:", cat.sound)
print("Type:", cat.type)
print("Color:", cat.color)

dog = Animals()

#The dot operator is used to acess the properties/characteristics of the objects.
dog.name = "Buddy"
dog.sound = "Woof"
dog.type = "Canine"
dog.color = "Brown"


print("\nName:", dog.name)
print("Sound:", dog.sound)
print("Type:", dog.type)
print("Color:", dog.color)










