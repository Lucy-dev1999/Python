#Static function has fixed value.
def add():
    var1 = 100
    var2 = 200
    return var1 + var2
print(add())

#Dynamic function expect values on the call of function.
#A variable within the braces of a function is called parameters.
#A parameter list is the number of parameters used in the parentheses of the function.
def add1(var1, var2):
    return var1 + var2

#The return grants access to the values of variables.
#Print is an inbuilt function. 
#The values of the parameters are called arguments.
print(add1(10, 20))
print(add1(20, 30))
print(add1(40, 50))
print(add1(60, 70))

#User defined functions are ones defined by the user.
#A parameter list is the number of parameters used in the parenthesis of the function.
#Both static and dynamic functions can return values.



    




